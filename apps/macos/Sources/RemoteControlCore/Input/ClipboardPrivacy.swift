public enum PasteboardMarker {
    public static let concealed = "org.nspasteboard.ConcealedType"
    public static let transient = "org.nspasteboard.TransientType"
    public static let autoGenerated = "org.nspasteboard.AutoGeneratedType"

    public static let privateTypes: Set<String> = [concealed, transient, autoGenerated]

    public static func isPrivate(_ types: [String]) -> Bool {
        types.contains(where: privateTypes.contains)
    }
}

public final class ClipboardSecrets: @unchecked Sendable {

    public static let shared = ClipboardSecrets()

    private let lock = NSLock()
    private var secrets: [[UInt8]] = []

    public init() {}

    public func replace(with values: [String]) {
        let normalized = values.map(Self.normalize).filter { !$0.isEmpty }
        lock.lock()
        secrets = normalized
        lock.unlock()
    }

    public func contains(in text: String) -> Bool {
        lock.lock()
        let current = secrets
        lock.unlock()
        guard !current.isEmpty else { return false }
        let haystack = Self.normalize(text)
        var found: UInt8 = 0
        for secret in current {
            found |= Self.constantTimeContains(haystack, secret)
        }
        return found != 0
    }

    static func normalize(_ text: String) -> [UInt8] {
        let alphabet = Set(CrockfordBase32.alphabet)
        return CrockfordBase32.normalize(text).filter(alphabet.contains).utf8.map { $0 }
    }

    static func constantTimeContains(_ haystack: [UInt8], _ needle: [UInt8]) -> UInt8 {
        guard !needle.isEmpty, haystack.count >= needle.count else { return 0 }
        var found: UInt8 = 0
        for start in 0...(haystack.count - needle.count) {
            var diff: UInt8 = 0
            for offset in 0..<needle.count {
                diff |= haystack[start + offset] ^ needle[offset]
            }
            found |= UInt8(diff == 0 ? 1 : 0)
        }
        return found
    }
}

#if canImport(AppKit)
@MainActor
public enum ConcealedPasteboard {

    nonisolated public static let defaultLifetime: TimeInterval = 60

    public static func write(_ text: String,
                             to pasteboard: NSPasteboard = .general,
                             clearAfter lifetime: TimeInterval = defaultLifetime) {
        pasteboard.clearContents()
        let item = NSPasteboardItem()
        item.setString(text, forType: .string)
        item.setData(Data(), forType: NSPasteboard.PasteboardType(PasteboardMarker.concealed))
        item.setData(Data(), forType: NSPasteboard.PasteboardType(PasteboardMarker.transient))
        pasteboard.writeObjects([item])
        let written = pasteboard.changeCount
        Task { @MainActor in
            try? await Task.sleep(nanoseconds: UInt64(lifetime * 1_000_000_000))
            guard pasteboard.changeCount == written else { return }
            pasteboard.clearContents()
        }
    }
}
#endif
