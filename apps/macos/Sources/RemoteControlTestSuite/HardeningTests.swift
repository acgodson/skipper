import Foundation
import RCTestKit
import RemoteControlCore

private let hostCode = "K7FM3Q8PW2XY"

private func payload<T: Decodable>(_ type: T.Type, _ json: String) -> T? {
    try? Envelope(type: "x", payload: Data(json.utf8)).decodePayload(type)
}

public let clipboardPrivacySuite = TestSuite("hardening/clipboard privacy", [

    TestCase("concealed, transient and auto-generated pasteboard items are never sent") {
        let engine = ClipboardSyncEngine(originId: "111111111", secrets: ClipboardSecrets())
        for marker in [PasteboardMarker.concealed, PasteboardMarker.transient, PasteboardMarker.autoGenerated] {
            try expectNil(engine.localChange(text: "hunter2", pasteboardTypes: ["public.utf8-plain-text", marker]),
                          "\(marker) must be skipped")
        }
        try expectEqual(engine.droppedPrivate, 3)
        try expectNotNil(engine.localChange(text: "hunter2", pasteboardTypes: ["public.utf8-plain-text"]),
                         "an ordinary copy of the same text still syncs")
    },

    TestCase("this Mac's access code is never sent, in any spelling or embedded in other text") {
        let secrets = ClipboardSecrets()
        secrets.replace(with: [hostCode])
        let engine = ClipboardSyncEngine(originId: "111111111", secrets: secrets)
        for pasted in [hostCode, "K7FM-3Q8P-W2XY", "k7fm 3q8p w2xy", "code: K7FM-3Q8P-W2XY thanks", "k7fm.3q8p.w2xy\n"] {
            try expectNil(engine.localChange(text: pasted), "'\(pasted)' must not leave this Mac")
        }
        try expectNotNil(engine.localChange(text: "K7FM-3Q8P-W2XZ"), "a different code is ordinary text")
    },

    TestCase("a refreshed code replaces the old one in the filter") {
        let secrets = ClipboardSecrets()
        secrets.replace(with: [hostCode])
        secrets.replace(with: ["ABCDABCDABCD"])
        try expectFalse(secrets.contains(in: hostCode))
        try expect(secrets.contains(in: "abcd-abcd-abcd"))
        secrets.replace(with: [])
        try expectFalse(secrets.contains(in: "ABCDABCDABCD"))
    },
])

public let wireClampSuite = TestSuite("hardening/wire clamps", [

    TestCase("scroll deltas that are non-finite or absurd are dropped at decode") {
        try expectNotNil(payload(ScrollPayload.self, #"{"dx":1.5,"dy":-3,"phase":"changed"}"#))
        try expectNil(payload(ScrollPayload.self, #"{"dx":1e300,"dy":0,"phase":"changed"}"#))
        try expectNil(payload(ScrollPayload.self, #"{"dx":0,"dy":-1e19,"phase":"changed"}"#))
    },

    TestCase("an injector handed non-finite values posts nothing") {
        let injector = InputInjector(target: InputDisplayTarget(bounds: CGRect(x: 0, y: 0, width: 100, height: 100)))
        try expectEqual(injector.scroll(ScrollPayload(dx: .infinity, dy: 0, phase: .changed)), [])
        try expectEqual(injector.scroll(ScrollPayload(dx: 0, dy: .nan, phase: .changed)), [])
        try expectEqual(injector.mouseMove(MouseMovePayload(x: .nan, y: 0.5, seq: 1)), [])
        try expectEqual(injector.click(ClickPayload(button: .left, x: 0.5, y: -.infinity, count: 1)), [])
        try expectEqual(injector.scroll(ScrollPayload(dx: 2, dy: 3, phase: .changed)).count, 1)
    },

    TestCase("the event sink refuses to build a scroll it cannot represent") {
        let sink = CGEventSink()
        for bad in [Double.infinity, -.infinity, .nan, 1e12] {
            try expectNil(sink.makeEvent(.scroll(.init(dx: bad, dy: 0, phase: .changed))), "dx \(bad)")
        }
        try expectNotNil(sink.makeEvent(.scroll(.init(dx: 4, dy: -4, phase: .changed))))
    },

    TestCase("display_info with a bad scale or size is dropped at decode") {
        try expectNotNil(payload(DisplayInfoPayload.self, #"{"w":2560,"h":1600,"scale":2}"#))
        try expectNil(payload(DisplayInfoPayload.self, #"{"w":2560,"h":1600,"scale":1e300}"#))
        try expectNil(payload(DisplayInfoPayload.self, #"{"w":2560,"h":1600,"scale":0}"#))
        try expectNil(payload(DisplayInfoPayload.self, #"{"w":0,"h":1600,"scale":2}"#))
        try expectNil(payload(DisplayInfoPayload.self, #"{"w":2560,"h":-1,"scale":2}"#))
    },

    TestCase("pointer coordinates far outside the display are dropped at decode") {
        try expectNotNil(payload(MouseMovePayload.self, #"{"x":0.5,"y":1.01,"seq":1}"#))
        try expectNil(payload(MouseMovePayload.self, #"{"x":1e308,"y":0,"seq":1}"#))
        try expectNil(payload(MouseButtonPayload.self, #"{"button":0,"x":0,"y":-1e10}"#))
        try expectNil(payload(ClickPayload.self, #"{"button":0,"x":1e20,"y":0,"count":1}"#))
    },

    TestCase("Double to integer conversion never traps") {
        try expectNil(WireBounds.int32(.nan))
        try expectNil(WireBounds.int32(1e10))
        try expectEqual(WireBounds.int32(-2.6), -3)
        try expectNil(WireBounds.int(.infinity))
        try expectNil(WireBounds.int(1e300))
        try expectEqual(WireBounds.int(2), 2)
    },
])

public let codeRotationSuite = TestSuite("hardening/access code rotation", [

    TestCase("refresh during a session ends the session before rotating") {
        var steps: [String] = []
        var open = true
        let rotation = AccessCodeRotation(
            sessionIsOpen: { open },
            endSession: { steps.append("end"); open = false },
            forceStop: { steps.append("force") },
            rotate: { steps.append(open ? "rotate-while-open" : "rotate") },
            pollInterval: 0.001, gracePeriod: 1)
        try await rotation.run()
        try expectEqual(steps, ["end", "rotate"])
    },

    TestCase("a session that will not close is cut off before the code rotates") {
        var steps: [String] = []
        var open = true
        let rotation = AccessCodeRotation(
            sessionIsOpen: { open },
            endSession: { steps.append("end") },
            forceStop: { steps.append("force"); open = false },
            rotate: { steps.append(open ? "rotate-while-open" : "rotate") },
            pollInterval: 0.001, gracePeriod: 0.02)
        try await rotation.run()
        try expectEqual(steps, ["end", "force", "rotate"])
    },

    TestCase("with no session the code simply rotates") {
        var steps: [String] = []
        let rotation = AccessCodeRotation(
            sessionIsOpen: { false },
            endSession: { steps.append("end") },
            forceStop: { steps.append("force") },
            rotate: { steps.append("rotate") })
        try await rotation.run()
        try expectEqual(steps, ["rotate"])
    },

    TestCase("any live, connecting or reconnecting session, or running capture, counts as open") {
        try expect(AccessCodeExposure.sessionIsOpen(phase: .live, captureState: .idle))
        try expect(AccessCodeExposure.sessionIsOpen(phase: .connecting, captureState: nil))
        try expect(AccessCodeExposure.sessionIsOpen(phase: .reconnecting, captureState: nil))
        try expect(AccessCodeExposure.sessionIsOpen(phase: .idle, captureState: .starting))
        try expect(AccessCodeExposure.sessionIsOpen(phase: .closed(reason: "x"),
                                                    captureState: .running(width: 1, height: 1, fps: 1)))
        try expectFalse(AccessCodeExposure.sessionIsOpen(phase: .idle, captureState: .idle))
        try expectFalse(AccessCodeExposure.sessionIsOpen(phase: nil, captureState: nil))
    },
])

public let backendOverrideSuite = TestSuite("hardening/backend overrides", [

    TestCase("API and web overrides are validated by the same rule") {
        for variable in [BackendOverrides.apiVariable, BackendOverrides.webVariable] {
            for good in ["https://dev.example.com", "http://localhost:8080", "http://127.0.0.1:18443"] {
                if case .failure = BackendOverrides.parse([variable: good]) { throw fail("\(variable)=\(good) must be accepted") }
            }
            for bad in ["http://dev.example.com", "ws://127.0.0.1:1", "ftp://localhost", "file:///tmp", "not a url", "http://localhost.evil.com"] {
                if case .success = BackendOverrides.parse([variable: bad]) { throw fail("\(variable)=\(bad) must be refused") }
            }
        }
    },

    TestCase("the development banner names every non-default host and nothing else") {
        let none = try BackendOverrides.parse([:]).get()
        try expectNil(none.developmentBannerText)
        let shipped = try BackendOverrides.parse([
            BackendOverrides.apiVariable: RCConfig.defaultAPIBaseURLString,
            BackendOverrides.webVariable: BackendOverrides.defaultWebBaseURLString,
        ]).get()
        try expectNil(shipped.developmentBannerText)
        let dev = try BackendOverrides.parse([
            BackendOverrides.apiVariable: "http://127.0.0.1:18443",
            BackendOverrides.webVariable: "https://web.dev.example.com",
        ]).get()
        try expectEqual(dev.developmentBannerText,
                        "Using a development server: 127.0.0.1:18443, web.dev.example.com")
    },
])
